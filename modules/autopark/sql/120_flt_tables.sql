-- Autopark module: fuel-tanker fleet automation for client Bemol.
-- Driver payroll by normative mileage, route/fuel control, supply planning.
-- Prefix: FLT_. Target database: platform cloud ADB (same as SDA).
--
-- All sequences use CACHE 20 -- a NOCACHE sequence under parallel
-- INSERT...SELECT produced ORA-12860 deadlocks on this ADB for the PECO
-- module (26.08.2026). Every PL/SQL block (trigger) is fenced by '/'
-- BEFORE and AFTER it -- without the leading '/' the shared splitter
-- glues the preceding CREATE TABLE/INDEX statements into the same PL/SQL
-- block, which cursor.execute() then rejects (SDA incident 25.08.2026).

-- Reference: petroleum products (A92/A95/A98/DIESEL). Natural key, no ID.
CREATE TABLE FLT_PRODUCTS (
  CODE      VARCHAR2(20)   NOT NULL,
  NAME_RU   VARCHAR2(120)  NOT NULL,
  ACTIVE    NUMBER(1)      DEFAULT 1 NOT NULL,
  CONSTRAINT PK_FLT_PRODUCTS PRIMARY KEY (CODE),
  CONSTRAINT CK_FLT_PRODUCTS_ACT CHECK (ACTIVE IN (0,1))
);

-- Fuel stations (AZS).
CREATE TABLE FLT_STATIONS (
  ID       NUMBER(12)     NOT NULL,
  CODE     VARCHAR2(20)   NOT NULL,
  NAME     VARCHAR2(200)  NOT NULL,
  ADDRESS  VARCHAR2(300),
  ACTIVE   NUMBER(1)      DEFAULT 1 NOT NULL,
  CONSTRAINT PK_FLT_STATIONS PRIMARY KEY (ID),
  CONSTRAINT CK_FLT_STATIONS_ACT CHECK (ACTIVE IN (0,1))
);
CREATE SEQUENCE SEQ_FLT_STATIONS START WITH 1 INCREMENT BY 1 CACHE 20;
/
CREATE OR REPLACE TRIGGER TRG_FLT_STATIONS_BI BEFORE INSERT ON FLT_STATIONS FOR EACH ROW
BEGIN IF :NEW.ID IS NULL THEN SELECT SEQ_FLT_STATIONS.NEXTVAL INTO :NEW.ID FROM DUAL; END IF; END;
/
CREATE UNIQUE INDEX UX_FLT_STATIONS_CODE ON FLT_STATIONS (CODE);

