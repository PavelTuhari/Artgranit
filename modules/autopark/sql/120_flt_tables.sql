-- Distance matrix between load points, stations and end points.
-- FROM_ID/TO_ID are polymorphic (their meaning depends on FROM_KIND/
-- TO_KIND), so no single FOREIGN KEY can target them -- application code
-- (modules/autopark/rules.py::route_legs) resolves FROM_KIND/TO_KIND to
-- the right table before doing a lookup.
CREATE TABLE FLT_DISTANCES (
  ID         NUMBER(12)    NOT NULL,
  FROM_KIND  VARCHAR2(10)  NOT NULL,
  FROM_ID    NUMBER(12)    NOT NULL,
  TO_KIND    VARCHAR2(10)  NOT NULL,
  TO_ID      NUMBER(12)    NOT NULL,
  KM         NUMBER(7,1)   NOT NULL,
  CONSTRAINT PK_FLT_DISTANCES PRIMARY KEY (ID),
  CONSTRAINT CK_FLT_DIST_FROM_KIND CHECK (FROM_KIND IN ('LOAD','STATION','END')),
  CONSTRAINT CK_FLT_DIST_TO_KIND CHECK (TO_KIND IN ('LOAD','STATION','END')),
  CONSTRAINT CK_FLT_DIST_KM CHECK (KM >= 0),
  CONSTRAINT UQ_FLT_DISTANCES UNIQUE (FROM_KIND, FROM_ID, TO_KIND, TO_ID)
);
CREATE SEQUENCE SEQ_FLT_DISTANCES START WITH 1 INCREMENT BY 1 CACHE 20;
/
CREATE OR REPLACE TRIGGER TRG_FLT_DISTANCES_BI BEFORE INSERT ON FLT_DISTANCES FOR EACH ROW
BEGIN IF :NEW.ID IS NULL THEN SELECT SEQ_FLT_DISTANCES.NEXTVAL INTO :NEW.ID FROM DUAL; END IF; END;
/

-- Trip type reference: DOMESTIC pays the 600 lei trip bonus, IMPORT does
