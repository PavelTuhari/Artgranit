-- Trips. A DRAFT trip is not yet payroll basis (ToR pt. 6): only an
-- APPROVED/DONE trip counts (see rules.py::payroll).
CREATE TABLE FLT_TRIPS (
  ID             NUMBER(12)    NOT NULL,
  TRIP_DATE      DATE          NOT NULL,
  TRUCK_ID       NUMBER(12)    NOT NULL,
  DRIVER_ID      NUMBER(12)    NOT NULL,
  TYPE_CODE      VARCHAR2(10)  NOT NULL,
  STATUS_CODE    VARCHAR2(10)  DEFAULT 'DRAFT' NOT NULL,
  LOAD_POINT_ID  NUMBER(12)    NOT NULL,
  END_POINT_ID   NUMBER(12)    NOT NULL,
  SOURCE         VARCHAR2(10)  DEFAULT 'MANUAL' NOT NULL,
  NORM_KM        NUMBER(8,1),
  FACT_KM        NUMBER(8,1),
  FACT_MINUTES   NUMBER(8),
  APPROVED_BY    VARCHAR2(120),
  CREATED_AT     DATE          DEFAULT SYSDATE NOT NULL,
  CONSTRAINT PK_FLT_TRIPS PRIMARY KEY (ID),
  CONSTRAINT FK_FLT_TRIPS_TRUCK FOREIGN KEY (TRUCK_ID) REFERENCES FLT_TRUCKS (ID),
  CONSTRAINT FK_FLT_TRIPS_DRIVER FOREIGN KEY (DRIVER_ID) REFERENCES FLT_DRIVERS (ID),
  CONSTRAINT FK_FLT_TRIPS_TYPE FOREIGN KEY (TYPE_CODE) REFERENCES FLT_REF_TRIP_TYPES (CODE),
  CONSTRAINT FK_FLT_TRIPS_STATUS FOREIGN KEY (STATUS_CODE) REFERENCES FLT_REF_TRIP_STATUS (CODE),
  CONSTRAINT FK_FLT_TRIPS_LOAD FOREIGN KEY (LOAD_POINT_ID) REFERENCES FLT_LOAD_POINTS (ID),
  CONSTRAINT FK_FLT_TRIPS_END FOREIGN KEY (END_POINT_ID) REFERENCES FLT_END_POINTS (ID),
