"""Мониторинг офиса: сеть и Telegram — изолированный модуль Artgranit.

Весь код модуля лежит здесь, в modules/netmon/. В общем коде портала модуль
не оставляет ничего: ядро (core/module_loader.py) находит пакет само и
подключает под /UNA.md/orasldev/netmon. Ядру нужен ровно один объект —
`blueprint`; маршруты объявлены в routes.py и импортируются ниже.

ВКЛЮЧАЕТСЯ ТОЛЬКО ЯВНО. Модуль показывает устройство офисной сети, доступы
к серверам и умеет выдавать ключи OpenVPN, поэтому на публичном портале ему
не место. Работает он там, где в `.env` стоит `NETMON_ENABLED=1`: на рабочей
машине администратора и на сервере мониторинга во внутренней сети.

Везде, где флага нет, ядро получает ПУСТОЙ blueprint: маршруты не
импортируются вовсе, поэтому нет ни страницы, ни API, ни пункта меню — адрес
отвечает 404. Сделано намеренно статично: включить модуль на сервере
случайно (деплоем, копированием каталога, чужой веткой) нельзя, нужна
осознанная правка `.env`, а `.env` в архив деплоя не входит.

Вторая линия — допустимые сети источника (routes._guard): даже включённый
модуль отвечает только запросам из локальной сети и туннеля.
"""
import os

from flask import Blueprint

ENABLED = os.environ.get("NETMON_ENABLED", "").strip() == "1"

blueprint = Blueprint("netmon", __name__, template_folder="templates")

if ENABLED:
    from modules.netmon import routes  # noqa: E402,F401  (регистрирует маршруты)

__all__ = ["blueprint", "ENABLED"]
