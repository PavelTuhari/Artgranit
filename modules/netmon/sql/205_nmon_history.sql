-- NMON_ история подключений: клиенты по дням, наши специалисты по событиям.
-- Ставится своим установщиком modules/netmon/scripts/netmon_deploy.py.
-- Без точки с запятой и апострофов в комментариях: общий разборщик режет по ним.
--
-- Откуда данные. Базы cloudbd и clouddev ведут аудит входов (DBA_AUDIT_SESSION),
-- но хранят его 30 дней. Журнал входов SSH сервера баз хранится 4 недели,
-- журнал сеансов (wtmp) с мая 2024. Модуль переносит всё это сюда, и история
-- не пропадает. Перенос повторяемый: строки сливаются по ключу.

-- Клиенты: входы за день по схеме, компьютеру и пользователю Windows
CREATE TABLE NMON_LOGON_DAY (
  DB          VARCHAR2(20)        NOT NULL,
  SCHEMA_NAME VARCHAR2(128)       NOT NULL,
  USERHOST    VARCHAR2(255 CHAR)  NOT NULL,
  OS_USER     VARCHAR2(255 CHAR)  NOT NULL,
  DAY         DATE                NOT NULL,
  CLIENT_KEY  VARCHAR2(60)        NOT NULL,
  LOGONS      NUMBER(10)          DEFAULT 0 NOT NULL,
  FAILED      NUMBER(10)          DEFAULT 0 NOT NULL,
  FIRST_AT    DATE,
  LAST_AT     DATE,
  CONSTRAINT PK_NMON_LOGON_DAY PRIMARY KEY (DB, SCHEMA_NAME, USERHOST, OS_USER, DAY)
);

CREATE INDEX IX_NMON_LOGON_DAY_CLIENT ON NMON_LOGON_DAY (CLIENT_KEY, DAY);

CREATE INDEX IX_NMON_LOGON_DAY_DAY ON NMON_LOGON_DAY (DAY);

-- Наши специалисты: каждый вход в базу и на сервер
-- SOURCE db — вход в базу (аудит), ssh — вход на сервер или сеанс
-- TARGET — база или сервер, ACCOUNT — схема или пользователь Linux
-- REF — ключ события в источнике, по нему повторный перенос не дублирует
CREATE TABLE NMON_STAFF_EVENT (
  ID          NUMBER GENERATED BY DEFAULT AS IDENTITY,
  SOURCE      VARCHAR2(10)        NOT NULL,
  TARGET      VARCHAR2(60)        NOT NULL,
  REF         VARCHAR2(160 CHAR)  NOT NULL,
  ACCOUNT     VARCHAR2(128 CHAR),
  FROM_HOST   VARCHAR2(255 CHAR),
  OS_USER     VARCHAR2(255 CHAR),
  START_AT    DATE                NOT NULL,
  END_AT      DATE,
  RESULT      VARCHAR2(10)        DEFAULT 'ok' NOT NULL,
  METHOD      VARCHAR2(80 CHAR),
  DETAIL      VARCHAR2(400 CHAR),
  OFF_HOURS   NUMBER(1)           DEFAULT 0 NOT NULL,
  AUTO        NUMBER(1)           DEFAULT 0 NOT NULL,
  CONSTRAINT PK_NMON_STAFF_EVENT PRIMARY KEY (ID),
  CONSTRAINT UK_NMON_STAFF_EVENT UNIQUE (SOURCE, TARGET, REF),
  CONSTRAINT CK_NMON_STAFF_EVENT_SRC CHECK (SOURCE IN ('db', 'ssh')),
  CONSTRAINT CK_NMON_STAFF_EVENT_RES CHECK (RESULT IN ('ok', 'fail'))
);

CREATE INDEX IX_NMON_STAFF_EVENT_START ON NMON_STAFF_EVENT (START_AT);

-- Первая установка 26.10.2026 создала METHOD на 40 байт, кириллица туда не влезла
ALTER TABLE NMON_STAFF_EVENT MODIFY (METHOD VARCHAR2(80 CHAR));

-- Кто наш. KIND: host — компьютер целиком, hostuser — компьютер и
-- пользователь Windows через черту (терминальный сервер общий),
-- ip — адрес входа по SSH, sshuser — пользователь Linux на сервере.
-- STAFF 1 — наш, 0 — явно не наш. ORIGIN auto — замечен с Toad или sqlplus.
CREATE TABLE NMON_STAFF_ID (
  KIND        VARCHAR2(10)        NOT NULL,
  VALUE       VARCHAR2(255 CHAR)  NOT NULL,
  STAFF       NUMBER(1)           DEFAULT 1 NOT NULL,
  PERSON      VARCHAR2(100 CHAR),
  NOTE        VARCHAR2(300 CHAR),
  ORIGIN      VARCHAR2(10)        DEFAULT 'manual' NOT NULL,
  UPDATED_AT  TIMESTAMP           DEFAULT SYSTIMESTAMP NOT NULL,
  UPDATED_BY  VARCHAR2(60),
  CONSTRAINT PK_NMON_STAFF_ID PRIMARY KEY (KIND, VALUE),
  CONSTRAINT CK_NMON_STAFF_ID_KIND CHECK (KIND IN ('host', 'hostuser', 'ip', 'sshuser'))
);

-- Последний перенос по каждому источнику
CREATE TABLE NMON_HIST_SYNC (
  SOURCE      VARCHAR2(30)        NOT NULL,
  LAST_AT     DATE,
  LAST_RUN    DATE,
  ROWS_IN     NUMBER,
  MESSAGE     VARCHAR2(1000 CHAR),
  CONSTRAINT PK_NMON_HIST_SYNC PRIMARY KEY (SOURCE)
);

