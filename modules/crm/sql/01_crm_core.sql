CREATE TABLE CRM_EVENT_LOG (
    ID         NUMBER         NOT NULL,
    TS         DATE           DEFAULT SYSDATE NOT NULL,
    CLIENT_ID  NUMBER,
    IDNO       VARCHAR2(20),
    EVENT      VARCHAR2(40)   NOT NULL,       -- added | dup | updated | deleted | import_error
    SRC        VARCHAR2(20),                  -- contragenti | return_to | xml | ui
    DETAIL     VARCHAR2(2000),
    CONSTRAINT PK_CRM_EVENT_LOG PRIMARY KEY (ID)
)
/

CREATE INDEX IX_CRM_EVENT_LOG_TS ON CRM_EVENT_LOG (TS)
