  SELECT CRM_FOUNDER_SEQ.NEXTVAL INTO :NEW.ID FROM dual;
END;
/

CREATE TABLE CRM_DEBT (
    ID         NUMBER        NOT NULL,
    CLIENT_ID  NUMBER        NOT NULL,
    NR         NUMBER,
    DEBT_TYPE  VARCHAR2(200),
    AMOUNT     NUMBER(14,2),
    CURRENCY   VARCHAR2(3)   DEFAULT 'MDL',
    CONSTRAINT PK_CRM_DEBT PRIMARY KEY (ID),
