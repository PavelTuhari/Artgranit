-- Контракты
CREATE TABLE PLG_CONTRACTS (
  ID              NUMBER        NOT NULL,
  SUPPLIER_ID     NUMBER        NOT NULL,
  CODE            VARCHAR2(40)  NOT NULL,   -- CTR-2026-2001
  CONTRACT_TYPE   VARCHAR2(20)  DEFAULT 'supply',
  TITLE_RU        VARCHAR2(300),
  TITLE_RO        VARCHAR2(300),
  TITLE_EN        VARCHAR2(300),
  DATE_FROM       DATE          NOT NULL,
  DATE_TO         DATE,
  CURRENCY        VARCHAR2(5)   DEFAULT 'MDL',
  PAYMENT_DAYS    NUMBER        DEFAULT 30, -- отсрочка платежа
  RETRO_BONUS_PCT NUMBER(5,2)   DEFAULT 0,  -- ретро-бонус
  DISCOUNT_PCT    NUMBER(5,2)   DEFAULT 0,
  MARKETING_FEE   NUMBER(14,2)  DEFAULT 0,
  MIN_ORDER_AMT   NUMBER(14,2),
  INCOTERMS       VARCHAR2(10)  DEFAULT 'DDP',
  LEAD_TIME_DAYS  NUMBER        DEFAULT 2,
  AUTO_RENEW      NUMBER(1)     DEFAULT 0,
  STATUS          VARCHAR2(20)  DEFAULT 'active',
  SIGNED_BY       VARCHAR2(150),
  FILE_URL        VARCHAR2(400),
  NOTES           VARCHAR2(1000),
  CREATED_AT      TIMESTAMP     DEFAULT SYSTIMESTAMP,
  UPDATED_AT      TIMESTAMP     DEFAULT SYSTIMESTAMP,
  CONSTRAINT PK_PLG_CONTRACTS PRIMARY KEY (ID),
  CONSTRAINT UQ_PLG_CTR_CODE UNIQUE (CODE),
  CONSTRAINT FK_PLG_CTR_SUP  FOREIGN KEY (SUPPLIER_ID) REFERENCES PLG_SUPPLIERS(ID) ON DELETE CASCADE,
  CONSTRAINT FK_PLG_CTR_TYPE FOREIGN KEY (CONTRACT_TYPE) REFERENCES PLG_REF_CONTRACT_TYPES(CODE),
  CONSTRAINT CHK_PLG_CTR_STATUS CHECK (STATUS IN ('draft','active','expired','terminated')),
  CONSTRAINT CHK_PLG_CTR_RENEW  CHECK (AUTO_RENEW IN (0,1))
);
/

CREATE OR REPLACE TRIGGER PLG_CONTRACTS_BI
  BEFORE INSERT ON PLG_CONTRACTS FOR EACH ROW
BEGIN
  IF :NEW.ID IS NULL THEN
    :NEW.ID := PLG_CONTRACTS_SEQ.NEXTVAL;
  END IF;
  IF :NEW.CODE IS NULL THEN
    :NEW.CODE := 'CTR-' || TO_CHAR(SYSDATE, 'YYYY') || '-' ||
                 TO_CHAR(PLG_CONTRACT_NUM_SEQ.NEXTVAL);
  END IF;
END;
/

CREATE OR REPLACE TRIGGER PLG_CONTRACTS_BU
  BEFORE UPDATE ON PLG_CONTRACTS FOR EACH ROW
BEGIN
  :NEW.UPDATED_AT := SYSTIMESTAMP;
END;
/

