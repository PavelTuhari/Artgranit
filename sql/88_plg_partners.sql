  NAME_RO    VARCHAR2(100) NOT NULL,
  NAME_EN    VARCHAR2(100) NOT NULL,
  SORT_ORDER NUMBER DEFAULT 0,
  CONSTRAINT PK_PLG_REF_CONTRACT_TYPES PRIMARY KEY (CODE)
);

CREATE TABLE PLG_REF_CONTACT_ROLES (
  CODE       VARCHAR2(20)  NOT NULL,   -- kam / logistics / finance / quality / director
