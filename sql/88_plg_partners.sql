-- ============================================================
-- Планограммы: партнёрский и рыночный контур
--
--   1. Поставщики: карточка, контакты, контракты, товарные группы работы
--   2. Конкуренты: сети, мониторинг их цен, их поставщики
--   3. Рынки: страны и схожие торговые сети для бенчмарка
--
-- Всё привязано к набору данных (DATASET_ID) и удаляется вместе с ним.
-- Данные наполняются генератором и правятся вручную в админке.
-- Префикс объектов: PLG_
-- ============================================================

CREATE SEQUENCE PLG_SUPPLIERS_SEQ     START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE PLG_SUP_CONTACTS_SEQ  START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE PLG_CONTRACTS_SEQ     START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE PLG_COMPETITORS_SEQ   START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE PLG_COMP_PRICES_SEQ   START WITH 1 INCREMENT BY 1 CACHE 1000;
CREATE SEQUENCE PLG_MARKETS_SEQ       START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE PLG_MKT_CHAINS_SEQ    START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE PLG_CONTRACT_NUM_SEQ  START WITH 2001 INCREMENT BY 1 NOCACHE;

-- ==================== Справочники ====================

