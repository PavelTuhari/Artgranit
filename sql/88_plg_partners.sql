-- ==================== Поставщики ====================

CREATE TABLE PLG_SUPPLIERS (
  ID              NUMBER        NOT NULL,
  DATASET_ID      NUMBER,
  CODE            VARCHAR2(30)  NOT NULL,
  NAME_RU         VARCHAR2(200) NOT NULL,
  NAME_RO         VARCHAR2(200),
  NAME_EN         VARCHAR2(200),
  SUPPLIER_TYPE   VARCHAR2(20)  DEFAULT 'distributor',
  COUNTRY         VARCHAR2(5)   DEFAULT 'MD',
  CITY            VARCHAR2(100),
  ADDRESS         VARCHAR2(400),
  IDNO            VARCHAR2(40),               -- фискальный код
  WEBSITE         VARCHAR2(200),
  PHONE           VARCHAR2(50),
  EMAIL           VARCHAR2(150),
  RATING          NUMBER(3,1),                -- 0..10, оценка надёжности
  OTIF_PCT        NUMBER(5,2),                -- on time in full, %
  ANNUAL_TURNOVER NUMBER(16,2),               -- годовой оборот с сетью
  SKU_COUNT       NUMBER        DEFAULT 0,
  IS_KEY          NUMBER(1)     DEFAULT 0,    -- ключевой поставщик
  DELIVERS_TO     VARCHAR2(20)  DEFAULT 'dc', -- dc / store / both
  STATUS          VARCHAR2(20)  DEFAULT 'active',
  CREATED_AT      TIMESTAMP     DEFAULT SYSTIMESTAMP,
  UPDATED_AT      TIMESTAMP     DEFAULT SYSTIMESTAMP,
  CONSTRAINT PK_PLG_SUPPLIERS PRIMARY KEY (ID),
  CONSTRAINT UQ_PLG_SUP_CODE UNIQUE (CODE),
  CONSTRAINT FK_PLG_SUP_DS   FOREIGN KEY (DATASET_ID) REFERENCES PLG_DATASETS(ID),
  CONSTRAINT FK_PLG_SUP_TYPE FOREIGN KEY (SUPPLIER_TYPE) REFERENCES PLG_REF_SUPPLIER_TYPES(CODE),
  CONSTRAINT CHK_PLG_SUP_STATUS   CHECK (STATUS IN ('active','on_hold','terminated','prospect')),
  CONSTRAINT CHK_PLG_SUP_KEY      CHECK (IS_KEY IN (0,1)),
  CONSTRAINT CHK_PLG_SUP_DELIVERS CHECK (DELIVERS_TO IN ('dc','store','both'))
);
/

CREATE OR REPLACE TRIGGER PLG_SUPPLIERS_BI
  BEFORE INSERT ON PLG_SUPPLIERS FOR EACH ROW
  WHEN (NEW.ID IS NULL)
BEGIN
  :NEW.ID := PLG_SUPPLIERS_SEQ.NEXTVAL;
END;
/

CREATE OR REPLACE TRIGGER PLG_SUPPLIERS_BU
  BEFORE UPDATE ON PLG_SUPPLIERS FOR EACH ROW
BEGIN
  :NEW.UPDATED_AT := SYSTIMESTAMP;
END;
/

