-- Зоны торгового зала с типом, категорией и актуальной проходимостью
CREATE OR REPLACE VIEW V_PLG_ZONES AS
SELECT
  z.ID, z.STORE_ID, s.CODE AS STORE_CODE,
  z.CODE, z.ZONE_TYPE,
  zt.NAME_RU AS ZONE_TYPE_RU, zt.NAME_RO AS ZONE_TYPE_RO, zt.NAME_EN AS ZONE_TYPE_EN,
  zt.IS_SELLING,
  z.CATEGORY_ID,
  c.NAME_RU AS CATEGORY_RU, c.NAME_RO AS CATEGORY_RO, c.NAME_EN AS CATEGORY_EN,
  z.NAME_RU, z.NAME_RO, z.NAME_EN,
  z.POS_X, z.POS_Y, z.WIDTH, z.HEIGHT,
  NVL(z.COLOR, zt.COLOR) AS COLOR,
  z.AREA_SQM, z.SORT_ORDER, z.STATUS,
  NVL(t.TRAFFIC_PCT, 0)  AS TRAFFIC_PCT,
  NVL(t.VISITORS, 0)     AS VISITORS,
  NVL(t.DWELL_SEC, 0)    AS DWELL_SEC,
  NVL(t.PICKUPS, 0)      AS PICKUPS,
  t.METRIC_DATE          AS TRAFFIC_DATE,
  CASE
    WHEN NVL(t.TRAFFIC_PCT, 0) >= 80 THEN 'peak'
    WHEN NVL(t.TRAFFIC_PCT, 0) >= 60 THEN 'high'
    WHEN NVL(t.TRAFFIC_PCT, 0) >= 40 THEN 'medium'
    ELSE 'low'
  END AS TRAFFIC_LEVEL,
  (SELECT COUNT(*) FROM PLG_FIXTURES f WHERE f.ZONE_ID = z.ID) AS FIXTURE_COUNT
FROM PLG_ZONES z
JOIN PLG_STORES s ON s.ID = z.STORE_ID
JOIN PLG_REF_ZONE_TYPES zt ON zt.CODE = z.ZONE_TYPE
LEFT JOIN PLG_CATEGORIES c ON c.ID = z.CATEGORY_ID
LEFT JOIN (
  SELECT zt2.ZONE_ID, zt2.TRAFFIC_PCT, zt2.VISITORS, zt2.DWELL_SEC, zt2.PICKUPS, zt2.METRIC_DATE
  FROM PLG_ZONE_TRAFFIC zt2
  WHERE zt2.METRIC_HOUR IS NULL
    AND zt2.METRIC_DATE = (
      SELECT MAX(zt3.METRIC_DATE) FROM PLG_ZONE_TRAFFIC zt3
      WHERE zt3.ZONE_ID = zt2.ZONE_ID AND zt3.METRIC_HOUR IS NULL
    )
) t ON t.ZONE_ID = z.ID;

-- Торговое оборудование с контекстом зоны и заполненностью полок
CREATE OR REPLACE VIEW V_PLG_FIXTURES AS
SELECT
  f.ID, f.STORE_ID, s.CODE AS STORE_CODE, f.ZONE_ID,
  z.NAME_RU AS ZONE_RU, z.NAME_RO AS ZONE_RO, z.NAME_EN AS ZONE_EN,
  f.CODE, f.FIXTURE_TYPE,
  ft.NAME_RU AS FIXTURE_TYPE_RU, ft.NAME_RO AS FIXTURE_TYPE_RO, ft.NAME_EN AS FIXTURE_TYPE_EN,
  ft.ICON,
  f.NAME_RU, f.NAME_RO, f.NAME_EN,
  f.POS_X, f.POS_Y, f.WIDTH, f.HEIGHT, f.ORIENTATION,
  f.SHELF_COUNT, f.WIDTH_MM, f.HEIGHT_MM, f.DEPTH_MM,
  f.SERIAL_NUMBER, f.STATUS, f.CREATED_AT, f.UPDATED_AT,
  (SELECT COUNT(*) FROM PLG_PLANOGRAM_ITEMS i WHERE i.FIXTURE_ID = f.ID) AS ITEM_COUNT,
  (SELECT NVL(SUM(i.FACINGS), 0) FROM PLG_PLANOGRAM_ITEMS i WHERE i.FIXTURE_ID = f.ID) AS FACING_COUNT
FROM PLG_FIXTURES f
JOIN PLG_STORES s ON s.ID = f.STORE_ID
JOIN PLG_REF_FIXTURE_TYPES ft ON ft.CODE = f.FIXTURE_TYPE
LEFT JOIN PLG_ZONES z ON z.ID = f.ZONE_ID;

-- Товары с категорией и участием в активных акциях
CREATE OR REPLACE VIEW V_PLG_PRODUCTS AS
SELECT
  p.ID, p.CODE, p.CATEGORY_ID,
  c.CODE AS CATEGORY_CODE,
  c.NAME_RU AS CATEGORY_RU, c.NAME_RO AS CATEGORY_RO, c.NAME_EN AS CATEGORY_EN,
  c.COLOR AS CATEGORY_COLOR,
  p.NAME_RU, p.NAME_RO, p.NAME_EN,
  p.BARCODE, p.BRAND, p.UOM, p.PRICE, p.CURRENCY,
  p.WIDTH_MM, p.HEIGHT_MM, p.DEPTH_MM, p.MIN_FACINGS, p.IMAGE_URL,
  p.STATUS, p.CREATED_AT, p.UPDATED_AT,
  (SELECT COUNT(*) FROM PLG_PLANOGRAM_ITEMS i WHERE i.PRODUCT_ID = p.ID) AS PLACEMENT_COUNT,
  (SELECT COUNT(*) FROM PLG_PROMO_PRODUCTS pp
     JOIN PLG_PROMOS pr ON pr.ID = pp.PROMO_ID
    WHERE pp.PRODUCT_ID = p.ID AND pr.STATUS = 'active') AS ACTIVE_PROMO_COUNT
FROM PLG_PRODUCTS p
LEFT JOIN PLG_CATEGORIES c ON c.ID = p.CATEGORY_ID;

-- Список планограмм (раздел «Список планограмм»)
CREATE OR REPLACE VIEW V_PLG_PLANOGRAMS AS
SELECT
  pl.ID, pl.CODE, pl.STORE_ID,
  s.CODE AS STORE_CODE,
  s.NAME_RU AS STORE_RU, s.NAME_RO AS STORE_RO, s.NAME_EN AS STORE_EN,
  pl.ZONE_ID,
  z.NAME_RU AS ZONE_RU, z.NAME_RO AS ZONE_RO, z.NAME_EN AS ZONE_EN,
  pl.NAME_RU, pl.NAME_RO, pl.NAME_EN,
  pl.VERSION_NO, pl.STATUS,
  st.NAME_RU AS STATUS_RU, st.NAME_RO AS STATUS_RO, st.NAME_EN AS STATUS_EN,
  st.COLOR AS STATUS_COLOR, st.IS_FINAL,
  pl.VALID_FROM, pl.VALID_TO, pl.AUTHOR, pl.APPROVED_BY, pl.APPROVED_AT,
  pl.NOTES, pl.SHELF_SHARE_PCT, pl.CREATED_AT, pl.UPDATED_AT,
  (SELECT COUNT(*) FROM PLG_PLANOGRAM_ITEMS i WHERE i.PLANOGRAM_ID = pl.ID) AS ITEM_COUNT,
  (SELECT NVL(SUM(i.FACINGS), 0) FROM PLG_PLANOGRAM_ITEMS i WHERE i.PLANOGRAM_ID = pl.ID) AS FACING_COUNT,
  (SELECT COUNT(DISTINCT i.PRODUCT_ID) FROM PLG_PLANOGRAM_ITEMS i WHERE i.PLANOGRAM_ID = pl.ID) AS SKU_COUNT,
  (SELECT MAX(h.CHANGED_AT) FROM PLG_PLANOGRAM_HISTORY h WHERE h.PLANOGRAM_ID = pl.ID) AS LAST_CHANGE_AT
FROM PLG_PLANOGRAMS pl
JOIN PLG_STORES s ON s.ID = pl.STORE_ID
JOIN PLG_REF_PLG_STATUSES st ON st.CODE = pl.STATUS
LEFT JOIN PLG_ZONES z ON z.ID = pl.ZONE_ID;

-- Позиции планограммы с товаром и оборудованием
CREATE OR REPLACE VIEW V_PLG_PLANOGRAM_ITEMS AS
SELECT
  i.ID, i.PLANOGRAM_ID, pl.CODE AS PLANOGRAM_CODE,
  i.FIXTURE_ID, f.CODE AS FIXTURE_CODE, f.FIXTURE_TYPE,
  i.PRODUCT_ID, p.CODE AS PRODUCT_CODE,
  p.NAME_RU AS PRODUCT_RU, p.NAME_RO AS PRODUCT_RO, p.NAME_EN AS PRODUCT_EN,
  p.BARCODE, p.BRAND, p.PRICE, p.CURRENCY, p.IMAGE_URL,
  p.CATEGORY_ID,
  c.NAME_RU AS CATEGORY_RU, c.NAME_RO AS CATEGORY_RO, c.NAME_EN AS CATEGORY_EN,
  c.COLOR AS CATEGORY_COLOR,
  i.SHELF_NO, i.POSITION_NO, i.FACINGS, i.DEPTH_QTY,
  i.X_MM, NVL(i.WIDTH_MM, p.WIDTH_MM * i.FACINGS) AS WIDTH_MM,
  i.IS_PROMO, i.NOTES, i.CREATED_AT
FROM PLG_PLANOGRAM_ITEMS i
JOIN PLG_PLANOGRAMS pl ON pl.ID = i.PLANOGRAM_ID
JOIN PLG_PRODUCTS p ON p.ID = i.PRODUCT_ID
LEFT JOIN PLG_FIXTURES f ON f.ID = i.FIXTURE_ID
LEFT JOIN PLG_CATEGORIES c ON c.ID = p.CATEGORY_ID;

-- История изменений планограмм
