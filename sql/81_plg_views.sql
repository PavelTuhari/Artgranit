SELECT
  h.ID, h.PLANOGRAM_ID, pl.CODE AS PLANOGRAM_CODE,
  pl.STORE_ID, s.CODE AS STORE_CODE,
  pl.NAME_RU AS PLANOGRAM_RU, pl.NAME_RO AS PLANOGRAM_RO, pl.NAME_EN AS PLANOGRAM_EN,
  h.VERSION_NO, h.ACTION, h.FIELD_NAME, h.OLD_VALUE, h.NEW_VALUE,
  h.SUMMARY_RU, h.SUMMARY_RO, h.SUMMARY_EN,
  h.CHANGED_BY, h.CHANGED_AT
FROM PLG_PLANOGRAM_HISTORY h
JOIN PLG_PLANOGRAMS pl ON pl.ID = h.PLANOGRAM_ID
JOIN PLG_STORES s ON s.ID = pl.STORE_ID;

-- Акции с вычисленным фактическим состоянием по датам
CREATE OR REPLACE VIEW V_PLG_PROMOS AS
SELECT
  pr.ID, pr.CODE, pr.STORE_ID, pr.PROMO_TYPE,
  pt.NAME_RU AS PROMO_TYPE_RU, pt.NAME_RO AS PROMO_TYPE_RO, pt.NAME_EN AS PROMO_TYPE_EN,
  pr.NAME_RU, pr.NAME_RO, pr.NAME_EN,
  pr.LABEL, pr.DISCOUNT_PCT, pr.DATE_FROM, pr.DATE_TO,
  NVL(pr.COLOR, pt.COLOR) AS COLOR,
  pr.STATUS,
  CASE
    WHEN pr.STATUS = 'cancelled' THEN 'cancelled'
    WHEN TRUNC(SYSDATE) BETWEEN pr.DATE_FROM AND pr.DATE_TO THEN 'active'
    WHEN TRUNC(SYSDATE) < pr.DATE_FROM THEN 'planned'
    ELSE 'finished'
  END AS EFFECTIVE_STATUS,
  pr.DATE_TO - TRUNC(SYSDATE) AS DAYS_LEFT,
  pr.CREATED_AT, pr.UPDATED_AT,
  (SELECT COUNT(*) FROM PLG_PROMO_PRODUCTS pp WHERE pp.PROMO_ID = pr.ID) AS PRODUCT_COUNT,
  (SELECT COUNT(*) FROM PLG_PROMO_ZONES pz WHERE pz.PROMO_ID = pr.ID) AS ZONE_COUNT
FROM PLG_PROMOS pr
JOIN PLG_REF_PROMO_TYPES pt ON pt.CODE = pr.PROMO_TYPE;

-- Топ категорий по проходимости за последнюю доступную дату
CREATE OR REPLACE VIEW V_PLG_TOP_CATEGORIES AS
SELECT
  m.STORE_ID, m.CATEGORY_ID, m.METRIC_DATE,
  c.CODE AS CATEGORY_CODE,
  c.NAME_RU, c.NAME_RO, c.NAME_EN, c.COLOR,
  m.VISITS, m.SALES_QTY, m.SALES_AMT,
  ROUND(RATIO_TO_REPORT(m.VISITS) OVER (PARTITION BY m.STORE_ID, m.METRIC_DATE) * 100) AS SHARE_PCT,
  ROW_NUMBER() OVER (PARTITION BY m.STORE_ID, m.METRIC_DATE ORDER BY m.VISITS DESC) AS RANK_NO,
  m.VISITS - NVL(prev.VISITS, m.VISITS) AS VISITS_DELTA,
  CASE WHEN NVL(prev.VISITS, 0) > 0
       THEN ROUND((m.VISITS - prev.VISITS) / prev.VISITS * 100, 1)
       ELSE 0 END AS DELTA_PCT
FROM PLG_CATEGORY_METRICS m
JOIN PLG_CATEGORIES c ON c.ID = m.CATEGORY_ID
LEFT JOIN PLG_CATEGORY_METRICS prev
       ON prev.STORE_ID = m.STORE_ID
      AND prev.CATEGORY_ID = m.CATEGORY_ID
      AND prev.METRIC_DATE = m.METRIC_DATE - 1;

-- Дневная динамика показателей магазина с приростом к предыдущему дню
CREATE OR REPLACE VIEW V_PLG_STORE_METRICS AS
SELECT
  m.ID, m.STORE_ID, s.CODE AS STORE_CODE, m.METRIC_DATE,
  m.TRAFFIC, m.BUYERS, m.CONVERSION_PCT, m.AVG_CHECK, m.REVENUE, m.CURRENCY,
  prev.TRAFFIC AS PREV_TRAFFIC,
  CASE WHEN NVL(prev.TRAFFIC, 0) > 0
       THEN ROUND((m.TRAFFIC - prev.TRAFFIC) / prev.TRAFFIC * 100, 1) ELSE 0 END AS TRAFFIC_DELTA_PCT,
  CASE WHEN NVL(prev.BUYERS, 0) > 0
       THEN ROUND((m.BUYERS - prev.BUYERS) / prev.BUYERS * 100, 1) ELSE 0 END AS BUYERS_DELTA_PCT,
  CASE WHEN NVL(prev.CONVERSION_PCT, 0) > 0
       THEN ROUND((m.CONVERSION_PCT - prev.CONVERSION_PCT) / prev.CONVERSION_PCT * 100, 1) ELSE 0 END AS CONV_DELTA_PCT,
  CASE WHEN NVL(prev.AVG_CHECK, 0) > 0
       THEN ROUND((m.AVG_CHECK - prev.AVG_CHECK) / prev.AVG_CHECK * 100, 1) ELSE 0 END AS CHECK_DELTA_PCT,
  CASE WHEN NVL(prev.REVENUE, 0) > 0
       THEN ROUND((m.REVENUE - prev.REVENUE) / prev.REVENUE * 100, 1) ELSE 0 END AS REVENUE_DELTA_PCT
FROM PLG_STORE_METRICS m
JOIN PLG_STORES s ON s.ID = m.STORE_ID
LEFT JOIN PLG_STORE_METRICS prev
       ON prev.STORE_ID = m.STORE_ID AND prev.METRIC_DATE = m.METRIC_DATE - 1;

-- Задачи мерчандайзинга с контекстом
CREATE OR REPLACE VIEW V_PLG_TASKS AS
SELECT
  t.ID, t.CODE, t.STORE_ID, s.CODE AS STORE_CODE,
  t.ZONE_ID, z.NAME_RU AS ZONE_RU, z.NAME_RO AS ZONE_RO, z.NAME_EN AS ZONE_EN,
  t.PLANOGRAM_ID, pl.CODE AS PLANOGRAM_CODE,
  t.TASK_TYPE,
  tt.NAME_RU AS TASK_TYPE_RU, tt.NAME_RO AS TASK_TYPE_RO, tt.NAME_EN AS TASK_TYPE_EN,
  tt.ICON,
  t.TITLE_RU, t.TITLE_RO, t.TITLE_EN, t.DESCRIPTION,
  t.PRIORITY, t.STATUS, t.ASSIGNEE, t.DUE_DATE, t.DONE_AT,
  t.CREATED_BY, t.CREATED_AT, t.UPDATED_AT,
  CASE WHEN t.DUE_DATE IS NOT NULL AND t.DUE_DATE < TRUNC(SYSDATE)
            AND t.STATUS NOT IN ('done','cancelled') THEN 1 ELSE 0 END AS IS_OVERDUE
FROM PLG_TASKS t
JOIN PLG_STORES s ON s.ID = t.STORE_ID
JOIN PLG_REF_TASK_TYPES tt ON tt.CODE = t.TASK_TYPE
LEFT JOIN PLG_ZONES z ON z.ID = t.ZONE_ID
LEFT JOIN PLG_PLANOGRAMS pl ON pl.ID = t.PLANOGRAM_ID;

