-- Сводка дашборда по каждому магазину (одна строка на магазин)
CREATE OR REPLACE VIEW V_PLG_DASHBOARD_STATS AS
SELECT
  s.ID AS STORE_ID, s.CODE AS STORE_CODE,
  s.NAME_RU AS STORE_RU, s.NAME_RO AS STORE_RO, s.NAME_EN AS STORE_EN,
  s.AREA_SQM, s.MAP_WIDTH, s.MAP_HEIGHT, s.CHECKOUT_QTY,
  (SELECT COUNT(*) FROM PLG_ZONES z WHERE z.STORE_ID = s.ID AND z.STATUS = 'active') AS ZONE_COUNT,
  (SELECT COUNT(*) FROM PLG_FIXTURES f WHERE f.STORE_ID = s.ID AND f.STATUS = 'active') AS FIXTURE_COUNT,
  (SELECT COUNT(*) FROM PLG_PLANOGRAMS p WHERE p.STORE_ID = s.ID) AS PLANOGRAM_COUNT,
  (SELECT COUNT(*) FROM PLG_PLANOGRAMS p WHERE p.STORE_ID = s.ID AND p.STATUS = 'active') AS PLANOGRAM_ACTIVE,
  (SELECT COUNT(*) FROM PLG_PLANOGRAMS p WHERE p.STORE_ID = s.ID AND p.STATUS IN ('draft','review')) AS PLANOGRAM_PENDING,
  (SELECT COUNT(DISTINCT i.PRODUCT_ID) FROM PLG_PLANOGRAM_ITEMS i
     JOIN PLG_PLANOGRAMS p ON p.ID = i.PLANOGRAM_ID WHERE p.STORE_ID = s.ID) AS SKU_COUNT,
  (SELECT COUNT(*) FROM PLG_PROMOS pr WHERE pr.STORE_ID = s.ID
     AND pr.STATUS <> 'cancelled' AND TRUNC(SYSDATE) BETWEEN pr.DATE_FROM AND pr.DATE_TO) AS PROMO_ACTIVE,
  (SELECT COUNT(*) FROM PLG_TASKS t WHERE t.STORE_ID = s.ID AND t.STATUS NOT IN ('done','cancelled')) AS TASK_OPEN,
  (SELECT COUNT(*) FROM PLG_TASKS t WHERE t.STORE_ID = s.ID
     AND t.STATUS NOT IN ('done','cancelled') AND t.DUE_DATE < TRUNC(SYSDATE)) AS TASK_OVERDUE,
  (SELECT COUNT(*) FROM PLG_NOTIFICATIONS n WHERE n.STORE_ID = s.ID AND n.IS_READ = 0) AS NOTIFY_UNREAD,
  (SELECT COUNT(*) FROM PLG_DOCUMENTS d WHERE d.STORE_ID = s.ID) AS DOC_COUNT,
  m.METRIC_DATE, m.TRAFFIC, m.BUYERS, m.CONVERSION_PCT, m.AVG_CHECK, m.REVENUE, m.CURRENCY
FROM PLG_STORES s
LEFT JOIN (
  SELECT m2.* FROM PLG_STORE_METRICS m2
  WHERE m2.METRIC_DATE = (
    SELECT MAX(m3.METRIC_DATE) FROM PLG_STORE_METRICS m3 WHERE m3.STORE_ID = m2.STORE_ID
  )
) m ON m.STORE_ID = s.ID;
