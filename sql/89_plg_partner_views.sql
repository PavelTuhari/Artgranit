-- ==================== Логистика ====================

-- Логистические центры со сводкой загрузки
CREATE OR REPLACE VIEW V_PLG_DC AS
SELECT
  d.ID, d.DATASET_ID, d.CODE, d.NAME_RU, d.NAME_RO, d.NAME_EN,
  d.CITY, d.ADDRESS_RU, d.ADDRESS_RO, d.ADDRESS_EN,
  d.AREA_SQM, d.DOCK_COUNT, d.PALLET_SLOTS, d.WORK_FROM, d.WORK_TO,
  d.HAS_FRESH, d.MANAGER_NAME, d.STATUS, d.CREATED_AT,
  (SELECT COUNT(*) FROM PLG_DC_STORES s WHERE s.DC_ID = d.ID)   AS STORE_COUNT,
  (SELECT COUNT(*) FROM PLG_VEHICLES v WHERE v.HOME_DC_ID = d.ID) AS VEHICLE_COUNT,
  (SELECT COUNT(*) FROM PLG_SHIPMENTS sh WHERE sh.DC_ID = d.ID
     AND sh.PLANNED_START >= TRUNC(SYSDATE) - 7)                 AS SHIPMENTS_7D,
  (SELECT NVL(SUM(sh.PALLETS), 0) FROM PLG_SHIPMENTS sh WHERE sh.DC_ID = d.ID
     AND sh.PLANNED_START >= TRUNC(SYSDATE) - 7)                 AS PALLETS_7D
FROM PLG_DC d;

-- Транспорт с типом и фактической загрузкой
CREATE OR REPLACE VIEW V_PLG_VEHICLES AS
SELECT
  v.ID, v.DATASET_ID, v.CODE, v.PLATE_NO, v.VEHICLE_TYPE,
  vt.NAME_RU AS VEHICLE_TYPE_NAME_RU, vt.NAME_RO AS VEHICLE_TYPE_NAME_RO,
  vt.NAME_EN AS VEHICLE_TYPE_NAME_EN,
  vt.COLOR, vt.ICON, vt.IS_REEFER,
  v.CARRIER, v.IS_OWN, v.DRIVER_NAME,
  NVL(v.CAPACITY_KG, vt.CAPACITY_KG)   AS CAPACITY_KG,
  NVL(v.VOLUME_M3, vt.VOLUME_M3)       AS VOLUME_M3,
  NVL(v.PALLET_SLOTS, vt.PALLET_SLOTS) AS PALLET_SLOTS,
  v.HOME_DC_ID, dc.CODE AS DC_CODE,
  dc.NAME_RU AS DC_RU, dc.NAME_RO AS DC_RO, dc.NAME_EN AS DC_EN,
  v.STATUS, v.CREATED_AT,
  (SELECT COUNT(*) FROM PLG_SHIPMENTS sh WHERE sh.VEHICLE_ID = v.ID
     AND sh.PLANNED_START >= TRUNC(SYSDATE) - 7) AS TRIPS_7D,
  (SELECT NVL(ROUND(SUM((CAST(sh.PLANNED_END AS DATE) - CAST(sh.PLANNED_START AS DATE)) * 24), 1), 0)
     FROM PLG_SHIPMENTS sh WHERE sh.VEHICLE_ID = v.ID
     AND sh.PLANNED_START >= TRUNC(SYSDATE) - 7) AS HOURS_7D
FROM PLG_VEHICLES v
JOIN PLG_REF_VEHICLE_TYPES vt ON vt.CODE = v.VEHICLE_TYPE
LEFT JOIN PLG_DC dc ON dc.ID = v.HOME_DC_ID;

-- Рейсы: основа диаграммы Ганта. Отдаёт готовые подписи полос и признак срыва окна.
CREATE OR REPLACE VIEW V_PLG_SHIPMENTS AS
SELECT
  sh.ID, sh.CODE, sh.SHIPMENT_TYPE,
  st.NAME_RU AS SHIPMENT_TYPE_NAME_RU, st.NAME_RO AS SHIPMENT_TYPE_NAME_RO,
  st.NAME_EN AS SHIPMENT_TYPE_NAME_EN, st.COLOR AS TYPE_COLOR,
  sh.SUPPLIER_ID, sup.CODE AS SUPPLIER_CODE,
  sup.NAME_RU AS SUPPLIER_RU, sup.NAME_RO AS SUPPLIER_RO, sup.NAME_EN AS SUPPLIER_EN,
  sh.DC_ID, dc.CODE AS DC_CODE,
  dc.NAME_RU AS DC_RU, dc.NAME_RO AS DC_RO, dc.NAME_EN AS DC_EN,
  sh.STORE_ID, s.CODE AS STORE_CODE,
  s.NAME_RU AS STORE_RU, s.NAME_RO AS STORE_RO, s.NAME_EN AS STORE_EN,
  sh.VEHICLE_ID, v.CODE AS VEHICLE_CODE, v.PLATE_NO, v.VEHICLE_TYPE,
  vt.NAME_RU AS VEHICLE_TYPE_NAME_RU, vt.NAME_RO AS VEHICLE_TYPE_NAME_RO,
  vt.NAME_EN AS VEHICLE_TYPE_NAME_EN, vt.COLOR AS VEHICLE_COLOR,
  NVL(s.DATASET_ID, NVL(dc.DATASET_ID, sup.DATASET_ID)) AS DATASET_ID,
  sh.DOCK_NO, sh.PLANNED_START, sh.PLANNED_END, sh.ACTUAL_START, sh.ACTUAL_END,
  sh.STATUS, sh.TEMP_MODE, sh.PALLETS, sh.WEIGHT_KG, sh.VOLUME_M3, sh.AMOUNT,
  sh.DISTANCE_KM, sh.DELAY_MIN, sh.NOTES,
  ROUND((CAST(sh.PLANNED_END AS DATE) - CAST(sh.PLANNED_START AS DATE)) * 24 * 60) AS PLANNED_MIN,
  ROUND((CAST(sh.ACTUAL_END AS DATE) - CAST(sh.ACTUAL_START AS DATE)) * 24 * 60)   AS ACTUAL_MIN,
  CASE WHEN sh.DELAY_MIN > 30 THEN 1 ELSE 0 END AS IS_LATE,
  (SELECT COUNT(*) FROM PLG_SHIPMENT_LINES l WHERE l.SHIPMENT_ID = sh.ID) AS LINE_COUNT
FROM PLG_SHIPMENTS sh
JOIN PLG_REF_SHIPMENT_TYPES st ON st.CODE = sh.SHIPMENT_TYPE
LEFT JOIN PLG_SUPPLIERS sup ON sup.ID = sh.SUPPLIER_ID
LEFT JOIN PLG_DC dc         ON dc.ID = sh.DC_ID
LEFT JOIN PLG_STORES s      ON s.ID = sh.STORE_ID
LEFT JOIN PLG_VEHICLES v    ON v.ID = sh.VEHICLE_ID
LEFT JOIN PLG_REF_VEHICLE_TYPES vt ON vt.CODE = v.VEHICLE_TYPE;

-- ==================== Поставщики ====================

CREATE OR REPLACE VIEW V_PLG_SUPPLIERS AS
SELECT
  sup.ID, sup.DATASET_ID, sup.CODE, sup.NAME_RU, sup.NAME_RO, sup.NAME_EN,
  sup.SUPPLIER_TYPE,
  t.NAME_RU AS SUPPLIER_TYPE_NAME_RU, t.NAME_RO AS SUPPLIER_TYPE_NAME_RO,
  t.NAME_EN AS SUPPLIER_TYPE_NAME_EN, t.COLOR AS TYPE_COLOR,
  sup.COUNTRY, sup.CITY, sup.ADDRESS, sup.IDNO, sup.WEBSITE, sup.PHONE, sup.EMAIL,
  sup.RATING, sup.OTIF_PCT, sup.ANNUAL_TURNOVER, sup.SKU_COUNT, sup.IS_KEY,
  sup.DELIVERS_TO, sup.STATUS, sup.CREATED_AT, sup.UPDATED_AT,
  (SELECT COUNT(*) FROM PLG_SUPPLIER_CONTACTS c WHERE c.SUPPLIER_ID = sup.ID)   AS CONTACT_COUNT,
  (SELECT COUNT(*) FROM PLG_CONTRACTS ct WHERE ct.SUPPLIER_ID = sup.ID)         AS CONTRACT_COUNT,
  (SELECT COUNT(*) FROM PLG_CONTRACTS ct WHERE ct.SUPPLIER_ID = sup.ID
     AND ct.STATUS = 'active')                                                  AS CONTRACT_ACTIVE,
  (SELECT COUNT(*) FROM PLG_SUPPLIER_CATEGORIES sc WHERE sc.SUPPLIER_ID = sup.ID) AS CATEGORY_COUNT,
  (SELECT COUNT(*) FROM PLG_PRODUCTS p WHERE p.SUPPLIER_ID = sup.ID)            AS PRODUCT_COUNT,
  (SELECT COUNT(*) FROM PLG_SHIPMENTS sh WHERE sh.SUPPLIER_ID = sup.ID
     AND sh.PLANNED_START >= TRUNC(SYSDATE) - 30)                               AS SHIPMENTS_30D,
  (SELECT MIN(ct.DATE_TO) FROM PLG_CONTRACTS ct WHERE ct.SUPPLIER_ID = sup.ID
     AND ct.STATUS = 'active' AND ct.DATE_TO IS NOT NULL)                       AS NEXT_EXPIRY,
  (SELECT c.FULL_NAME FROM PLG_SUPPLIER_CONTACTS c
     WHERE c.SUPPLIER_ID = sup.ID AND c.IS_PRIMARY = 1 AND ROWNUM = 1)          AS PRIMARY_CONTACT,
  (SELECT c.PHONE FROM PLG_SUPPLIER_CONTACTS c
     WHERE c.SUPPLIER_ID = sup.ID AND c.IS_PRIMARY = 1 AND ROWNUM = 1)          AS PRIMARY_PHONE
FROM PLG_SUPPLIERS sup
JOIN PLG_REF_SUPPLIER_TYPES t ON t.CODE = sup.SUPPLIER_TYPE;

CREATE OR REPLACE VIEW V_PLG_SUPPLIER_CONTACTS AS
SELECT
  c.ID, c.SUPPLIER_ID, sup.CODE AS SUPPLIER_CODE,
  sup.NAME_RU AS SUPPLIER_RU, sup.NAME_RO AS SUPPLIER_RO, sup.NAME_EN AS SUPPLIER_EN,
  c.FULL_NAME, c.ROLE_CODE,
  r.NAME_RU AS ROLE_NAME_RU, r.NAME_RO AS ROLE_NAME_RO, r.NAME_EN AS ROLE_NAME_EN, r.ICON,
  c.POSITION_TX, c.PHONE, c.MOBILE, c.EMAIL, c.MESSENGER, c.IS_PRIMARY, c.NOTES, c.CREATED_AT
FROM PLG_SUPPLIER_CONTACTS c
