-- ==================== Рынки ====================

CREATE OR REPLACE VIEW V_PLG_MARKETS AS
SELECT
  m.ID, m.DATASET_ID, m.COUNTRY_CODE, m.NAME_RU, m.NAME_RO, m.NAME_EN,
  m.POPULATION_MLN, m.GDP_PER_CAPITA, m.CURRENCY, m.RETAIL_VOLUME_MLN,
  m.MODERN_TRADE_PCT, m.TOP5_SHARE_PCT, m.AVG_CHECK, m.AVG_CHECK_EUR,
  m.STORES_PER_100K, m.PRIVATE_LABEL_PCT, m.NOTES, m.CREATED_AT,
  (SELECT COUNT(*) FROM PLG_MARKET_CHAINS ch WHERE ch.MARKET_ID = m.ID) AS CHAIN_COUNT,
  (SELECT NVL(SUM(ch.STORE_COUNT), 0) FROM PLG_MARKET_CHAINS ch WHERE ch.MARKET_ID = m.ID) AS STORES_TOTAL,
  (SELECT ROUND(AVG(ch.PRIVATE_LABEL_PCT), 2) FROM PLG_MARKET_CHAINS ch WHERE ch.MARKET_ID = m.ID) AS AVG_PL_PCT,
  (SELECT MAX(ch.NAME) FROM PLG_MARKET_CHAINS ch WHERE ch.MARKET_ID = m.ID
     AND ch.MARKET_SHARE_PCT = (SELECT MAX(ch2.MARKET_SHARE_PCT) FROM PLG_MARKET_CHAINS ch2
                                 WHERE ch2.MARKET_ID = m.ID)) AS LEADER_CHAIN
FROM PLG_MARKETS m;

CREATE OR REPLACE VIEW V_PLG_MARKET_CHAINS AS
SELECT
  ch.ID, ch.MARKET_ID, m.DATASET_ID, m.COUNTRY_CODE,
  m.NAME_RU AS MARKET_RU, m.NAME_RO AS MARKET_RO, m.NAME_EN AS MARKET_EN,
  ch.NAME, ch.OWNER_GROUP, ch.FORMAT_MIX, ch.STORE_COUNT, ch.REVENUE_MLN,
  ch.MARKET_SHARE_PCT, ch.AVG_STORE_SQM, ch.SKU_COUNT, ch.PRIVATE_LABEL_PCT,
  ch.AVG_CHECK_EUR, ch.ONLINE_SHARE_PCT, ch.LOYALTY_PROGRAM, ch.IS_BENCHMARK, ch.NOTES,
  CASE WHEN NVL(ch.STORE_COUNT, 0) > 0
       THEN ROUND(ch.REVENUE_MLN / ch.STORE_COUNT, 3) END AS REVENUE_PER_STORE_MLN,
  CASE WHEN NVL(ch.AVG_STORE_SQM, 0) > 0 AND NVL(ch.STORE_COUNT, 0) > 0
       THEN ROUND(ch.REVENUE_MLN * 1000000 / (ch.STORE_COUNT * ch.AVG_STORE_SQM), 0) END AS REVENUE_PER_SQM
FROM PLG_MARKET_CHAINS ch
JOIN PLG_MARKETS m ON m.ID = ch.MARKET_ID;
