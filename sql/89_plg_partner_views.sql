-- ==================== Конкуренты ====================

CREATE OR REPLACE VIEW V_PLG_COMPETITORS AS
SELECT
  cm.ID, cm.DATASET_ID, cm.CODE, cm.NAME_RU, cm.NAME_RO, cm.NAME_EN,
  cm.COUNTRY, cm.FORMAT_MIX, cm.STORE_COUNT, cm.POSITIONING, cm.PRICE_INDEX,
  cm.MARKET_SHARE, cm.ANNUAL_REVENUE, cm.PRIVATE_LABEL_PCT, cm.WEBSITE,
  NVL(cm.COLOR, '#64748b') AS COLOR, cm.STATUS, cm.CREATED_AT,
  (SELECT COUNT(*) FROM PLG_COMPETITOR_PRICES p WHERE p.COMPETITOR_ID = cm.ID) AS PRICE_CHECKS,
  (SELECT MAX(p.CHECK_DATE) FROM PLG_COMPETITOR_PRICES p WHERE p.COMPETITOR_ID = cm.ID) AS LAST_CHECK,
  (SELECT COUNT(DISTINCT p.PRODUCT_ID) FROM PLG_COMPETITOR_PRICES p WHERE p.COMPETITOR_ID = cm.ID) AS SKU_MONITORED,
  (SELECT COUNT(*) FROM PLG_COMPETITOR_SUPPLIERS cs WHERE cs.COMPETITOR_ID = cm.ID) AS SUPPLIER_COUNT,
  (SELECT COUNT(*) FROM PLG_COMPETITOR_SUPPLIERS cs WHERE cs.COMPETITOR_ID = cm.ID
     AND cs.SUPPLIER_ID IS NOT NULL) AS SHARED_SUPPLIERS,
  (SELECT ROUND(AVG(p.PRICE / NULLIF(p.OUR_PRICE, 0)) * 100, 2)
     FROM PLG_COMPETITOR_PRICES p WHERE p.COMPETITOR_ID = cm.ID
     AND p.CHECK_DATE = (SELECT MAX(p2.CHECK_DATE) FROM PLG_COMPETITOR_PRICES p2
                          WHERE p2.COMPETITOR_ID = cm.ID)) AS PRICE_INDEX_ACTUAL
FROM PLG_COMPETITORS cm;

-- Сравнение цен по SKU на последнюю дату замера
CREATE OR REPLACE VIEW V_PLG_PRICE_COMPARE AS
SELECT
  p.COMPETITOR_ID, cm.CODE AS COMPETITOR_CODE,
  cm.NAME_RU AS COMPETITOR_RU, cm.NAME_RO AS COMPETITOR_RO, cm.NAME_EN AS COMPETITOR_EN,
  NVL(cm.COLOR, '#64748b') AS COMPETITOR_COLOR, cm.DATASET_ID,
  p.PRODUCT_ID, pr.CODE AS PRODUCT_CODE,
  pr.NAME_RU AS PRODUCT_RU, pr.NAME_RO AS PRODUCT_RO, pr.NAME_EN AS PRODUCT_EN,
  pr.ABC_CLASS, pr.CATEGORY_ID,
  c.NAME_RU AS CATEGORY_RU, c.NAME_RO AS CATEGORY_RO, c.NAME_EN AS CATEGORY_EN,
  c.COLOR AS CATEGORY_COLOR,
  p.CHECK_DATE, p.PRICE AS COMPETITOR_PRICE, p.OUR_PRICE, p.IS_PROMO, p.IN_STOCK,
  p.SOURCE, p.CITY,
  ROUND(p.PRICE - p.OUR_PRICE, 2) AS DIFF_ABS,
  ROUND(p.PRICE / NULLIF(p.OUR_PRICE, 0) * 100, 2) AS PRICE_INDEX,
  CASE
    WHEN p.OUR_PRICE IS NULL OR p.OUR_PRICE = 0 THEN 'unknown'
    WHEN p.PRICE < p.OUR_PRICE * 0.97 THEN 'we_expensive'
    WHEN p.PRICE > p.OUR_PRICE * 1.03 THEN 'we_cheap'
    ELSE 'parity'
  END AS POSITION_CODE
FROM PLG_COMPETITOR_PRICES p
JOIN PLG_COMPETITORS cm ON cm.ID = p.COMPETITOR_ID
JOIN PLG_PRODUCTS pr    ON pr.ID = p.PRODUCT_ID
LEFT JOIN PLG_CATEGORIES c ON c.ID = pr.CATEGORY_ID
WHERE p.CHECK_DATE = (SELECT MAX(p2.CHECK_DATE) FROM PLG_COMPETITOR_PRICES p2
                       WHERE p2.COMPETITOR_ID = p.COMPETITOR_ID);

-- Ценовой индекс по категориям: одна строка на «конкурент × товарная группа»
CREATE OR REPLACE VIEW V_PLG_PRICE_INDEX_CAT AS
SELECT
  v.DATASET_ID, v.COMPETITOR_ID, v.COMPETITOR_CODE,
  v.COMPETITOR_RU, v.COMPETITOR_RO, v.COMPETITOR_EN, v.COMPETITOR_COLOR,
  v.CATEGORY_ID, v.CATEGORY_RU, v.CATEGORY_RO, v.CATEGORY_EN, v.CATEGORY_COLOR,
  COUNT(*) AS SKU_COUNT,
  ROUND(AVG(v.PRICE_INDEX), 2) AS PRICE_INDEX,
  ROUND(MIN(v.PRICE_INDEX), 2) AS INDEX_MIN,
  ROUND(MAX(v.PRICE_INDEX), 2) AS INDEX_MAX,
  SUM(CASE WHEN v.POSITION_CODE = 'we_expensive' THEN 1 ELSE 0 END) AS WE_EXPENSIVE,
  SUM(CASE WHEN v.POSITION_CODE = 'we_cheap' THEN 1 ELSE 0 END)     AS WE_CHEAP,
  SUM(CASE WHEN v.POSITION_CODE = 'parity' THEN 1 ELSE 0 END)       AS PARITY,
  SUM(v.IS_PROMO) AS PROMO_COUNT,
  MAX(v.CHECK_DATE) AS CHECK_DATE
FROM V_PLG_PRICE_COMPARE v
WHERE v.CATEGORY_ID IS NOT NULL
GROUP BY v.DATASET_ID, v.COMPETITOR_ID, v.COMPETITOR_CODE,
         v.COMPETITOR_RU, v.COMPETITOR_RO, v.COMPETITOR_EN, v.COMPETITOR_COLOR,
         v.CATEGORY_ID, v.CATEGORY_RU, v.CATEGORY_RO, v.CATEGORY_EN, v.CATEGORY_COLOR;

