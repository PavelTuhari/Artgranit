LEFT JOIN PLG_REF_CONTACT_ROLES r ON r.CODE = c.ROLE_CODE;

CREATE OR REPLACE VIEW V_PLG_CONTRACTS AS
SELECT
  ct.ID, ct.SUPPLIER_ID, sup.CODE AS SUPPLIER_CODE, sup.DATASET_ID,
  sup.NAME_RU AS SUPPLIER_RU, sup.NAME_RO AS SUPPLIER_RO, sup.NAME_EN AS SUPPLIER_EN,
  ct.CODE, ct.CONTRACT_TYPE,
  t.NAME_RU AS CONTRACT_TYPE_NAME_RU, t.NAME_RO AS CONTRACT_TYPE_NAME_RO,
  t.NAME_EN AS CONTRACT_TYPE_NAME_EN,
  ct.TITLE_RU, ct.TITLE_RO, ct.TITLE_EN,
  ct.DATE_FROM, ct.DATE_TO, ct.CURRENCY, ct.PAYMENT_DAYS, ct.RETRO_BONUS_PCT,
  ct.DISCOUNT_PCT, ct.MARKETING_FEE, ct.MIN_ORDER_AMT, ct.INCOTERMS,
  ct.LEAD_TIME_DAYS, ct.AUTO_RENEW, ct.STATUS, ct.SIGNED_BY, ct.FILE_URL, ct.NOTES,
  ct.CREATED_AT, ct.UPDATED_AT,
  CASE WHEN ct.DATE_TO IS NULL THEN NULL ELSE ct.DATE_TO - TRUNC(SYSDATE) END AS DAYS_LEFT,
  CASE
    WHEN ct.STATUS <> 'active' THEN ct.STATUS
    WHEN ct.DATE_TO IS NOT NULL AND ct.DATE_TO < TRUNC(SYSDATE) THEN 'expired'
    ELSE 'active'
  END AS EFFECTIVE_STATUS,
  CASE WHEN ct.STATUS = 'active' AND ct.DATE_TO IS NOT NULL
            AND ct.DATE_TO BETWEEN TRUNC(SYSDATE) AND TRUNC(SYSDATE) + 60
       THEN 1 ELSE 0 END AS EXPIRING_SOON
FROM PLG_CONTRACTS ct
JOIN PLG_SUPPLIERS sup ON sup.ID = ct.SUPPLIER_ID
JOIN PLG_REF_CONTRACT_TYPES t ON t.CODE = ct.CONTRACT_TYPE;

