  CONSTRAINT UQ_TBC_FLOWS_CODE UNIQUE (CODE),
  CONSTRAINT FK_TBC_FL_SDEV  FOREIGN KEY (SRC_DEVICE_ID) REFERENCES TBC_DEVICES(ID) ON DELETE CASCADE,
  CONSTRAINT FK_TBC_FL_SNODE FOREIGN KEY (SRC_NODE_ID) REFERENCES TBC_NODES(ID) ON DELETE CASCADE,
  CONSTRAINT FK_TBC_FL_DNODE FOREIGN KEY (DST_NODE_ID) REFERENCES TBC_NODES(ID) ON DELETE CASCADE,
  CONSTRAINT CHK_TBC_FL_KIND CHECK (SRC_KIND IN ('device','node')),
