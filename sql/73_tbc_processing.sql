-- ==================== Представления ====================

CREATE OR REPLACE VIEW V_TBC_NODES AS
SELECT
  n.ID, n.CODE, n.NAME, n.NODE_TYPE, n.STORE_ID,
  s.CODE AS STORE_CODE, s.NAME AS STORE_NAME,
  n.HOSTNAME, n.IP_ADDRESS, n.OS, n.STATUS,
  n.CPU_PCT, n.RAM_PCT, n.DISK_PCT,
  n.APP_NAME, n.APP_VERSION, n.APP_STATUS,
  n.DB_ENGINE, n.DB_VERSION, n.DB_STATUS, n.DB_SIZE_MB, n.DB_CONNECTIONS,
  n.LAST_SEEN, n.UPDATED_AT,
  (SELECT COUNT(*) FROM TBC_FLOWS f WHERE (f.SRC_NODE_ID = n.ID OR f.DST_NODE_ID = n.ID)) AS FLOW_COUNT,
  (SELECT COUNT(*) FROM TBC_FLOWS f WHERE (f.SRC_NODE_ID = n.ID OR f.DST_NODE_ID = n.ID)
     AND f.STATUS IN ('STALLED','FAIL')) AS FLOW_PROBLEMS
FROM TBC_NODES n
LEFT JOIN TBC_STORES s ON s.ID = n.STORE_ID;

CREATE OR REPLACE VIEW V_TBC_FLOWS AS
SELECT
  f.ID, f.CODE, f.NAME, f.SRC_KIND, f.FLOW_TYPE, f.SCHEDULE_MIN,
  f.SRC_DEVICE_ID, d.CODE AS SRC_DEVICE_CODE, d.STATUS AS SRC_DEVICE_STATUS,
  f.SRC_NODE_ID, sn.CODE AS SRC_NODE_CODE, sn.STATUS AS SRC_NODE_STATUS,
  f.DST_NODE_ID, dn.CODE AS DST_NODE_CODE, dn.NODE_TYPE AS DST_NODE_TYPE, dn.STATUS AS DST_NODE_STATUS,
  COALESCE(d.CODE, sn.CODE) AS SRC_CODE,
  COALESCE(ds.CODE, ss.CODE) AS STORE_CODE,
  f.STATUS, f.LAG_MIN, f.PENDING_ROWS, f.LAST_OK_AT, f.LAST_ERROR, f.UPDATED_AT,
  (SELECT COUNT(*) FROM TBC_FLOW_LOG l WHERE l.FLOW_ID = f.ID AND l.STATUS = 'FAIL'
     AND l.STARTED_AT > SYSTIMESTAMP - 1) AS FAILS_24H
FROM TBC_FLOWS f
LEFT JOIN TBC_DEVICES d ON d.ID = f.SRC_DEVICE_ID
LEFT JOIN TBC_STORES ds ON ds.ID = d.STORE_ID
LEFT JOIN TBC_NODES sn ON sn.ID = f.SRC_NODE_ID
LEFT JOIN TBC_STORES ss ON ss.ID = sn.STORE_ID
JOIN TBC_NODES dn ON dn.ID = f.DST_NODE_ID;

CREATE OR REPLACE VIEW V_TBC_PROC_STATS AS
SELECT
  (SELECT COUNT(*) FROM TBC_FLOWS) AS FLOWS_TOTAL,
  (SELECT COUNT(*) FROM TBC_FLOWS WHERE STATUS = 'OK') AS FLOWS_OK,
  (SELECT COUNT(*) FROM TBC_FLOWS WHERE STATUS = 'LAGGING') AS FLOWS_LAGGING,
  (SELECT COUNT(*) FROM TBC_FLOWS WHERE STATUS = 'STALLED') AS FLOWS_STALLED,
  (SELECT COUNT(*) FROM TBC_FLOWS WHERE STATUS = 'FAIL') AS FLOWS_FAIL,
  (SELECT NVL(SUM(PENDING_ROWS), 0) FROM TBC_FLOWS) AS PENDING_TOTAL,
  (SELECT NVL(MAX(LAG_MIN), 0) FROM TBC_FLOWS) AS MAX_LAG_MIN,
  (SELECT COUNT(*) FROM TBC_NODES) AS NODES_TOTAL,
  (SELECT COUNT(*) FROM TBC_NODES WHERE STATUS = 'online') AS NODES_ONLINE,
  (SELECT COUNT(*) FROM TBC_NODES WHERE STATUS = 'offline') AS NODES_OFFLINE,
  (SELECT COUNT(*) FROM TBC_NODES WHERE DB_STATUS = 'FAIL') AS NODES_DB_FAIL,
  (SELECT COUNT(*) FROM TBC_FLOW_LOG WHERE STATUS = 'FAIL' AND STARTED_AT > SYSTIMESTAMP - 1) AS BATCH_FAILS_24H,
  (SELECT COUNT(*) FROM TBC_AI_DOSSIERS) AS DOSSIERS_TOTAL,
  (SELECT COUNT(*) FROM TBC_AI_DOSSIERS WHERE STATUS = 'new') AS DOSSIERS_NEW
FROM DUAL;
