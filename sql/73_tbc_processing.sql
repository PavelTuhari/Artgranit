CREATE SEQUENCE TBC_METRICS_SEQ  START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE TBC_NODES_SEQ    START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE TBC_FLOWS_SEQ    START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE TBC_FLOW_LOG_SEQ START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE TBC_DOSSIERS_SEQ START WITH 1 INCREMENT BY 1 NOCACHE;

-- ==================== Time series метрик касс (раздел 72) ====================

CREATE TABLE TBC_METRIC_SAMPLES (
  ID         NUMBER       NOT NULL,
  DEVICE_ID  NUMBER       NOT NULL,
  SCOPE      VARCHAR2(5)  NOT NULL,     -- hw (касса-компьютер) / app (Front Office)
  METRIC     VARCHAR2(30) NOT NULL,     -- cpu/ram/disk/uptime | app_latency/tx_count/app_errors
  NUM_VALUE  NUMBER,
  SAMPLED_AT TIMESTAMP    DEFAULT SYSTIMESTAMP,
  CONSTRAINT PK_TBC_METRICS PRIMARY KEY (ID),
  CONSTRAINT FK_TBC_MS_DEVICE FOREIGN KEY (DEVICE_ID) REFERENCES TBC_DEVICES(ID) ON DELETE CASCADE,
  CONSTRAINT CHK_TBC_MS_SCOPE CHECK (SCOPE IN ('hw','app'))
);
/

CREATE OR REPLACE TRIGGER TBC_METRICS_BI
  BEFORE INSERT ON TBC_METRIC_SAMPLES FOR EACH ROW
  WHEN (NEW.ID IS NULL)
BEGIN
  :NEW.ID := TBC_METRICS_SEQ.NEXTVAL;
END;
/

CREATE INDEX IX_TBC_MS_DEV ON TBC_METRIC_SAMPLES (DEVICE_ID, SCOPE, METRIC, SAMPLED_AT);

-- ==================== Узлы обработки (раздел 73.3) ====================

CREATE TABLE TBC_NODES (
  ID             NUMBER        NOT NULL,
  CODE           VARCHAR2(40)  NOT NULL,   -- MD-CHS-001-ISRV-A, CENTRAL-01, BACKOFFICE-01
  NAME           VARCHAR2(200) NOT NULL,
  NODE_TYPE      VARCHAR2(20)  NOT NULL,   -- store_srv / central / backoffice
  STORE_ID       NUMBER,                   -- NULL для central/backoffice
  HOSTNAME       VARCHAR2(100),
  IP_ADDRESS     VARCHAR2(45),
  OS             VARCHAR2(50),
  STATUS         VARCHAR2(20)  DEFAULT 'offline',
  CPU_PCT        NUMBER,
  RAM_PCT        NUMBER,
  DISK_PCT       NUMBER,
  APP_NAME       VARCHAR2(100),            -- сервис обмена/консолидации
  APP_VERSION    VARCHAR2(30),
  APP_STATUS     VARCHAR2(10)  DEFAULT 'UNKNOWN',   -- OK/WARN/FAIL/UNKNOWN
  DB_ENGINE      VARCHAR2(20),             -- oracle/sqlite/mssql/mysql/postgres
  DB_VERSION     VARCHAR2(50),
  DB_STATUS      VARCHAR2(10)  DEFAULT 'UNKNOWN',
  DB_SIZE_MB     NUMBER,
  DB_CONNECTIONS NUMBER,
  LAST_SEEN      TIMESTAMP,
  CREATED_AT     TIMESTAMP     DEFAULT SYSTIMESTAMP,
  UPDATED_AT     TIMESTAMP     DEFAULT SYSTIMESTAMP,
  CONSTRAINT PK_TBC_NODES PRIMARY KEY (ID),
  CONSTRAINT UQ_TBC_NODES_CODE UNIQUE (CODE),
  CONSTRAINT FK_TBC_ND_STORE FOREIGN KEY (STORE_ID) REFERENCES TBC_STORES(ID),
  CONSTRAINT CHK_TBC_ND_TYPE CHECK (NODE_TYPE IN ('store_srv','central','backoffice')),
  CONSTRAINT CHK_TBC_ND_STATUS CHECK (STATUS IN ('online','degraded','offline','maintenance')),
  CONSTRAINT CHK_TBC_ND_ENGINE CHECK (DB_ENGINE IN ('oracle','sqlite','mssql','mysql','postgres'))
