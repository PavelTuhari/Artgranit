  ID            NUMBER        NOT NULL,
  CODE          VARCHAR2(60)  NOT NULL,
  NAME          VARCHAR2(200),
  SRC_KIND      VARCHAR2(10)  NOT NULL,   -- device (касса, SQLite) / node (сервер)
  SRC_DEVICE_ID NUMBER,
  SRC_NODE_ID   NUMBER,
  DST_NODE_ID   NUMBER        NOT NULL,
  FLOW_TYPE     VARCHAR2(20)  DEFAULT 'sales',   -- sales/docs/prices/stock/sync
  SCHEDULE_MIN  NUMBER        DEFAULT 15,        -- периодичность обмена, мин
  STATUS        VARCHAR2(10)  DEFAULT 'OK',      -- OK/LAGGING/STALLED/FAIL
  LAG_MIN       NUMBER        DEFAULT 0,
  PENDING_ROWS  NUMBER        DEFAULT 0,
  LAST_OK_AT    TIMESTAMP,
  LAST_ERROR    VARCHAR2(500),
  UPDATED_AT    TIMESTAMP     DEFAULT SYSTIMESTAMP,
