-- ==================== Master data ====================

-- Магазины
CREATE TABLE TBC_STORES (
  ID              NUMBER        NOT NULL,
  CODE            VARCHAR2(30)  NOT NULL,      -- MD-CHS-001
  NAME            VARCHAR2(200) NOT NULL,
  COUNTRY         VARCHAR2(5)   DEFAULT 'MD',
  CITY            VARCHAR2(100),
  ADDRESS         VARCHAR2(500),
  TIMEZONE        VARCHAR2(50)  DEFAULT 'Europe/Chisinau',
  STATUS          VARCHAR2(20)  DEFAULT 'active',
  MAINT_DOW       NUMBER,                      -- день недели maintenance window (1=Пн..7=Вс)
  MAINT_TIME_FROM VARCHAR2(5),                 -- '02:00'
  MAINT_TIME_TO   VARCHAR2(5),                 -- '04:00'
  CREATED_AT      TIMESTAMP     DEFAULT SYSTIMESTAMP,
  UPDATED_AT      TIMESTAMP     DEFAULT SYSTIMESTAMP,
  CONSTRAINT PK_TBC_STORES PRIMARY KEY (ID),
  CONSTRAINT UQ_TBC_STORES_CODE UNIQUE (CODE),
  CONSTRAINT CHK_TBC_STORE_STATUS CHECK (STATUS IN ('active','inactive','maintenance'))
);
/

CREATE OR REPLACE TRIGGER TBC_STORES_BI
  BEFORE INSERT ON TBC_STORES FOR EACH ROW
