  ID              NUMBER        NOT NULL,
  CODE            VARCHAR2(40)  NOT NULL,      -- MD-CHS-001-POS-01
  STORE_ID        NUMBER        NOT NULL,
  DEVICE_TYPE     VARCHAR2(10)  NOT NULL,      -- POS/SCO/AND/SRV/NET/PRN
  HOSTNAME        VARCHAR2(100),
  SERIAL_NUMBER   VARCHAR2(100),
  ASSET_ID        VARCHAR2(50),
  MANUFACTURER    VARCHAR2(100),
  MODEL           VARCHAR2(100),
  OS              VARCHAR2(50),                -- Windows / Android / Linux
  OS_VERSION      VARCHAR2(50),
  IP_ADDRESS      VARCHAR2(45),
  MAC_ADDRESS     VARCHAR2(20),
  INSTALL_DATE    DATE,
  STATUS          VARCHAR2(20)  DEFAULT 'offline',
  OWNER_SIDE      VARCHAR2(20)  DEFAULT 'customer',  -- customer / developer
  SUPPORT_GROUP   VARCHAR2(30),
  CRITICALITY     VARCHAR2(10)  DEFAULT 'medium',
  CPU_PCT         NUMBER,
  RAM_PCT         NUMBER,
  DISK_PCT        NUMBER,
  BATTERY_PCT     NUMBER,                      -- только Android
  STORAGE_FREE_MB NUMBER,
  PENDING_OPS     NUMBER        DEFAULT 0,
  LAST_SEEN       TIMESTAMP,
  LAST_SYNC       TIMESTAMP,
  CREATED_AT      TIMESTAMP     DEFAULT SYSTIMESTAMP,
  UPDATED_AT      TIMESTAMP     DEFAULT SYSTIMESTAMP,
  CONSTRAINT PK_TBC_DEVICES PRIMARY KEY (ID),
  CONSTRAINT UQ_TBC_DEVICES_CODE UNIQUE (CODE),
  CONSTRAINT FK_TBC_DEV_STORE FOREIGN KEY (STORE_ID) REFERENCES TBC_STORES(ID),
  CONSTRAINT FK_TBC_DEV_TYPE  FOREIGN KEY (DEVICE_TYPE) REFERENCES TBC_REF_DEVICE_TYPES(CODE),
  CONSTRAINT FK_TBC_DEV_GRP   FOREIGN KEY (SUPPORT_GROUP) REFERENCES TBC_REF_SUPPORT_GROUPS(CODE),
  CONSTRAINT CHK_TBC_DEV_STATUS CHECK (STATUS IN ('online','degraded','offline','maintenance')),
  CONSTRAINT CHK_TBC_DEV_CRIT   CHECK (CRITICALITY IN ('high','medium','low'))
