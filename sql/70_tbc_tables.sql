  CONSTRAINT FK_TBC_EV_DEVICE FOREIGN KEY (DEVICE_ID) REFERENCES TBC_DEVICES(ID),
  CONSTRAINT FK_TBC_EV_SVC    FOREIGN KEY (SERVICE_CODE) REFERENCES TBC_REF_SERVICES(CODE),
  CONSTRAINT FK_TBC_EV_PARENT FOREIGN KEY (PARENT_EVENT_ID) REFERENCES TBC_EVENTS(ID),
