  STORE_ID        NUMBER,
  DEVICE_ID       NUMBER,
  SERVICE_CODE    VARCHAR2(30),
  PROBLEM         VARCHAR2(500) NOT NULL,
  STATUS          VARCHAR2(20)  DEFAULT 'open',
  SOURCE          VARCHAR2(30)  DEFAULT 'zabbix',   -- zabbix/agent/manual/correlation
