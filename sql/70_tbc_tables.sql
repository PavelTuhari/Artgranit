BEGIN
  :NEW.ID := TBC_STORES_SEQ.NEXTVAL;
END;
/

CREATE OR REPLACE TRIGGER TBC_STORES_BU
  BEFORE UPDATE ON TBC_STORES FOR EACH ROW
BEGIN
  :NEW.UPDATED_AT := SYSTIMESTAMP;
END;
/

-- Устройства (технический паспорт, раздел 9 ТЗ)
